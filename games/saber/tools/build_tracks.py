"""
Regenerate games/saber/tracks.js from the music in games/saber/assets/music.

  python games/saber/tools/build_tracks.py

Runs analyze.py on every track listed below and writes the beat grid, per-bar loudness and
per-16th onset strength into tracks.js (a classic script: window.CadenceTracks).
"""
import json, os, sys
sys.path.insert(0, os.path.dirname(__file__))
import analyze  # noqa: E402

ROOT = os.path.join(os.path.dirname(__file__), '..')
# bpm: set when the autocorrelation picks a 4:3 or 2:1 relative of the real tempo (checked by grid fit)
TRACKS = [
    {'file': 'the-rush.ogg', 'bpm': None},
    {'file': 'evasion.ogg', 'bpm': 100.0},
    {'file': 'thrust-sequence.ogg', 'bpm': None},
    {'file': 'winning-the-race.ogg', 'bpm': None},
    {'file': 'darker-waves.ogg', 'bpm': None},
]

out = {}
for t in TRACKS:
    r = analyze.analyse(os.path.join(ROOT, 'assets', 'music', t['file']), t['bpm'])
    print(t['file'], r['bpm'], r['offset'], len(r['bars']), 'fit', r['fit'])
    out[t['file']] = r

with open(os.path.join(ROOT, 'tracks.js'), 'w') as f:
    f.write('/* Generated by tools/build_tracks.py from assets/music - do not edit by hand. */\n')
    f.write('(function (g) { g.CadenceTracks = ')
    json.dump(out, f, separators=(',', ':'))
    f.write('; })(typeof window !== "undefined" ? window : this);\n')
